import 'package:flutter/widgets.dart';
import 'package:provider/provider.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// Interface language chosen in Settings. English strings are the keys.
class AppText extends ChangeNotifier {
  AppText(SharedPreferences preferences)
    : _preferences = preferences,
      code = _stored(preferences);

  static const storageKey = 'app.language';
  static const supportedLocales = <Locale>[
    Locale('en'),
    Locale('ru'),
    Locale('es'),
    Locale('de'),
    Locale('fr'),
  ];

  static const options = <(String, String)>[
    ('en', 'English'),
    ('ru', 'Русский'),
    ('es', 'Español'),
    ('de', 'Deutsch'),
    ('fr', 'Français'),
  ];

  final SharedPreferences _preferences;
  String code;

  static String _stored(SharedPreferences preferences) {
    final stored = preferences.getString(storageKey);
    if (stored == 'ru' ||
        stored == 'es' ||
        stored == 'de' ||
        stored == 'fr' ||
        stored == 'en') {
      return stored!;
    }
    if (stored != null) {
      preferences.setString(storageKey, 'en');
    }
    return 'en';
  }

  static AppText? maybeOf(BuildContext context) {
    try {
      return Provider.of<AppText>(context);
    } on ProviderNotFoundException {
      return null;
    }
  }

  String translate(String english) {
    if (code == 'en') return english;
    return _tables[code]?[english] ?? english;
  }

  Future<void> select(String next) async {
    if (next == code || !_tables.containsKey(next) && next != 'en') return;
    code = next;
    notifyListeners();
    await _preferences.setString(storageKey, next);
  }
}

extension AppTextContext on BuildContext {
  String tr(String english) => AppText.maybeOf(this)?.translate(english) ?? english;
}

