import 'dart:io';

/// Switches the iOS target and the Dart brand before a build.
///
/// Run from the project root:
/// `dart run tool/select_brand.dart zenith`
/// `dart run tool/select_brand.dart ancient`
/// `dart run tool/select_brand.dart apex`
void main(List<String> args) {
  final name = args.isEmpty ? '' : args.first.toLowerCase();
  final brand = _brands[name];
  if (brand == null) {
    stderr.writeln(
      'Usage: dart run tool/select_brand.dart <zenith|ancient|apex>',
    );
    exitCode = 64;
    return;
  }

  final root = Directory.current;
  File('${root.path}/ios/Flutter/Brand.xcconfig')
      .writeAsStringSync(_xcconfig(brand));
  File('${root.path}/lib/core/config/active_brand.dart')
      .writeAsStringSync(_activeBrand(brand));
  _copyLaunchImage(root, brand);

  stdout.writeln('Active brand: ${brand.displayName}');
  stdout.writeln('Bundle ID: ${brand.bundleId}');
  stdout.writeln('Home screen name: ${brand.displayName}');
  stdout.writeln('App icon set: ${brand.iconSet}');
  stdout.writeln('Support email: ${brand.supportEmail}');
  stdout.writeln('Next flutter run / flutter build ipa uses this brand.');
}

final _brands = <String, _Brand>{
  'ancient': _ancient,
  'ancientcodex': _ancient,
  'zenith': _zenith,
  'zenithhabits': _zenith,
  'apex': _apex,
  'apexcalc': _apex,
};

const _ancient = _Brand(
  idName: 'ancientCodex',
  displayName: 'Ancient Codex',
  bundleId: 'com.ancientcodex.app',
  iconSet: 'AppIconAncient',
  supportEmail: 'dev.outbox.88@outlook.com',
);

const _zenith = _Brand(
  idName: 'zenithHabits',
  displayName: 'Zenith Habits',
  bundleId: 'com.zenithhabits.app',
  iconSet: 'AppIconZenith',
  supportEmail: 'dev.outbox.88@outlook.com',
);

const _apex = _Brand(
  idName: 'apexCalc',
  displayName: 'Apex Calc',
  bundleId: 'com.apexcalc.app',
  iconSet: 'AppIconApex',
  supportEmail: 'dev.outbox.88@outlook.com',
);

class _Brand {
  const _Brand({
    required this.idName,
    required this.displayName,
    required this.bundleId,
    required this.iconSet,
    required this.supportEmail,
  });

  final String idName;
  final String displayName;
  final String bundleId;
  final String iconSet;
  final String supportEmail;
}

String _xcconfig(_Brand brand) {
  return [
    '// Generated by tool/select_brand.dart.',
    '// SUPPORT_EMAIL is read by Info.plist and the Settings screen.',
    '// Editing that line updates both on the next build.',
    'APP_DISPLAY_NAME=${brand.displayName}',
    'PRODUCT_NAME=${brand.displayName}',
    'PRODUCT_BUNDLE_IDENTIFIER=${brand.bundleId}',
    'RUNNER_TEST_BUNDLE_ID=${brand.bundleId}.RunnerTests',
    'ASSETCATALOG_COMPILER_APPICON_NAME=${brand.iconSet}',
    'SUPPORT_EMAIL=${brand.supportEmail}',
    '',
  ].join('\n');
}

String _activeBrand(_Brand brand) {
  return [
    '/// Active product selected by `dart run tool/select_brand.dart`.',
    '///',
    '/// `activeBrandSupportEmail` matches `SUPPORT_EMAIL` in Brand.xcconfig.',
    "const String activeBrandIdName = '${brand.idName}';",
    "const String activeBrandSupportEmail = '${brand.supportEmail}';",
    '',
  ].join('\n');
}

void _copyLaunchImage(Directory root, _Brand brand) {
  final source = Directory(
    '${root.path}/ios/Runner/LaunchBrands/${brand.iconSet}',
  );
  final destination = Directory(
    '${root.path}/ios/Runner/Assets.xcassets/LaunchImage.imageset',
  );
  if (!source.existsSync()) return;
  for (final name in ['LaunchImage.png', 'LaunchImage@2x.png', 'LaunchImage@3x.png']) {
    final file = File('${source.path}/$name');
    if (!file.existsSync()) continue;
    file.copySync('${destination.path}/$name');
  }
}
